import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = path.join(repoRoot, 'registry.json');
const contractsDir = path.join(repoRoot, 'components', 'contracts');
const cssDir = path.join(repoRoot, 'components', 'css');
const cssIndexPath = path.join(cssDir, 'index.css');
const jsSourcePath = path.join(repoRoot, 'components', 'js', 'theme.js');
const webDir = path.join(repoRoot, 'platforms', 'web');

const outputPaths = {
  entry: path.join(webDir, 'index.css'),
  tokens: path.join(webDir, 'tokens.css'),
  components: path.join(webDir, 'components.css'),
  javascript: path.join(webDir, 'theme.js'),
  manifest: path.join(webDir, 'adapter.manifest.json'),
  summary: path.join(webDir, 'adapter.summary.json')
};

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function readJson(filePath) {
  return JSON.parse(read(filePath));
}

function write(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

function relative(filePath) {
  return path.relative(repoRoot, filePath);
}

function readCssOrder() {
  const indexCss = read(cssIndexPath);
  const imports = [...indexCss.matchAll(/@import\s+['"]([^'"]+\.css)['"];/g)].map((match) => match[1]);

  assert(imports.length > 0, 'components/css/index.css does not contain any CSS imports');

  return imports;
}

function readContracts() {
  const contracts = new Map();
  const files = fs.readdirSync(contractsDir).filter((fileName) => fileName.endsWith('.contract.json')).sort();

  for (const fileName of files) {
    const contract = readJson(path.join(contractsDir, fileName));
    contracts.set(contract.slug, contract);
  }

  return contracts;
}

function flattenPublicTokens(contract) {
  return [...new Set(Object.values(contract.tokens?.public ?? {}).flat())].sort();
}

function groupComponentsByCssFile(registry) {
  const byFile = new Map();

  for (const [slug, component] of Object.entries(registry.components)) {
    const list = byFile.get(component.file) ?? [];
    list.push(slug);
    byFile.set(component.file, list);
  }

  return byFile;
}

function sourceRole(fileName, registry) {
  const filePath = `components/css/${fileName}`;
  const baseEntry = Object.entries(registry.base).find(([, entry]) => entry.file === filePath);

  if (baseEntry) {
    return `base:${baseEntry[0]}`;
  }

  const categoryEntry = Object.entries(registry.categories).find(([, entry]) => entry.file === filePath);

  if (categoryEntry) {
    return `category:${categoryEntry[0]}`;
  }

  return 'component-source';
}

function buildComponentsCss(cssFiles) {
  const sections = [
    '/* ============================================================',
    '   The Gallery - Neutral Web Component CSS',
    '   Generated by scripts/build-web-adapter.js from components/css/.',
    '   Do not edit this file directly; change components/css/ instead.',
    '   ============================================================ */',
    ''
  ];

  for (const fileName of cssFiles) {
    const sourcePath = path.join(cssDir, fileName);
    assert(fs.existsSync(sourcePath), `${relative(sourcePath)} does not exist`);

    sections.push(
      `/* Source: components/css/${fileName} */`,
      read(sourcePath).trimEnd(),
      ''
    );
  }

  write(outputPaths.components, `${sections.join('\n')}\n`);
}

function buildIndexCss() {
  const content = [
    '/* ============================================================',
    '   The Gallery - Neutral Web Entry',
    '   Generated by scripts/build-web-adapter.js.',
    '   Load this file for the complete neutral web adapter.',
    '   ============================================================ */',
    '',
    "@import './tokens.css';",
    "@import './components.css';",
    ''
  ].join('\n');

  write(outputPaths.entry, content);
}

function copyThemeJs() {
  assert(fs.existsSync(jsSourcePath), `${relative(jsSourcePath)} does not exist`);
  write(outputPaths.javascript, read(jsSourcePath));
}

function buildManifest(registry, contracts, cssFiles) {
  const componentsByFile = groupComponentsByCssFile(registry);
  const components = [];
  const uniquePublicTokens = new Set();
  let implementedComponents = 0;
  let behaviorComponents = 0;

  for (const [slug, registryComponent] of Object.entries(registry.components)) {
    const contract = contracts.get(slug);

    assert(contract, `${slug} is missing a component contract`);
    assert(contract.adapters?.web?.status === 'implemented', `${slug} does not mark the web adapter as implemented`);

    const publicTokens = flattenPublicTokens(contract);
    for (const token of publicTokens) {
      uniquePublicTokens.add(token);
    }

    if ((contract.behavior ?? []).length > 0) {
      behaviorComponents += 1;
    }

    implementedComponents += 1;

    components.push({
      slug,
      name: contract.name,
      registryId: contract.registryId,
      category: contract.category,
      status: contract.status,
      selector: registryComponent.selector,
      source: {
        contract: `components/contracts/${slug}.contract.json`,
        css: registryComponent.file,
        docs: contract.source.docs
      },
      dependencies: registryComponent.dependencies ?? [],
      variants: contract.variants.map((variant) => ({
        name: variant.name,
        className: variant.className,
        default: variant.default
      })),
      sizes: contract.sizes.map((size) => ({
        name: size.name,
        className: size.className,
        default: size.default
      })),
      anatomy: contract.anatomy.map((part) => ({
        name: part.name,
        selector: part.selector,
        className: part.className ?? null,
        required: part.required,
        generated: part.generated ?? false
      })),
      states: contract.states.map((state) => ({
        name: state.name,
        selectors: state.selectors
      })),
      behavior: (contract.behavior ?? []).map((behavior) => ({
        name: behavior.name,
        selectors: behavior.selectors ?? [],
        attributes: behavior.attributes ?? [],
        events: behavior.events ?? []
      })),
      publicTokens,
      adapter: contract.adapters.web
    });
  }

  const outputs = {
    entry: relative(outputPaths.entry),
    tokens: relative(outputPaths.tokens),
    components: relative(outputPaths.components),
    javascript: relative(outputPaths.javascript),
    manifest: relative(outputPaths.manifest),
    summary: relative(outputPaths.summary)
  };

  const loadOrder = [
    {
      type: 'stylesheet',
      path: relative(outputPaths.tokens),
      required: true,
      reason: 'Provides canonical --tg-* variables and public compatibility aliases.'
    },
    {
      type: 'stylesheet',
      path: relative(outputPaths.components),
      required: true,
      reason: 'Provides the current hand-authored web component implementation.'
    },
    {
      type: 'script',
      path: relative(outputPaths.javascript),
      required: false,
      reason: 'Adds progressive enhancement for current shared web interactions.'
    }
  ];

  const policy = {
    componentImplementation: 'Hand-authored CSS from components/css is the current neutral web adapter implementation.',
    contractRole: 'Component contracts validate and describe the adapter; they do not generate component CSS yet.',
    distribution: 'Consumer projects copy and own these files locally.'
  };

  const stats = {
    components: components.length,
    implementedComponents,
    componentsWithBehavior: behaviorComponents,
    cssFiles: cssFiles.length,
    uniquePublicTokens: uniquePublicTokens.size
  };

  const categoryCoverage = Object.entries(
    components.reduce((acc, component) => {
      acc[component.category] = (acc[component.category] ?? 0) + 1;
      return acc;
    }, {})
  )
    .map(([category, count]) => ({ category, count }))
    .sort((a, b) => a.category.localeCompare(b.category));

  const manifest = {
    $schema: 'https://the-gallery.dev/schema/web-adapter-manifest.json',
    manifestVersion: '0.1.0',
    target: {
      id: 'web',
      name: 'Neutral Web',
      kind: 'css',
      status: 'active',
      description: 'Target-neutral CSS and progressive-enhancement JavaScript generated from The Gallery source facts.'
    },
    generatedBy: 'scripts/build-web-adapter.js',
    source: {
      registry: 'registry.json',
      contracts: 'components/contracts',
      tokens: 'tokens/source',
      css: 'components/css',
      javascript: 'components/js/theme.js'
    },
    outputs,
    loadOrder,
    policy,
    sources: {
      cssFiles: cssFiles.map((fileName) => {
        const source = `components/css/${fileName}`;

        return {
          source,
          role: sourceRole(fileName, registry),
          output: relative(outputPaths.components),
          components: componentsByFile.get(source) ?? []
        };
      })
    },
    stats,
    components
  };

  const summary = {
    $schema: 'https://the-gallery.dev/schema/web-adapter-summary.json',
    summaryVersion: '0.1.0',
    target: manifest.target,
    outputs,
    loadOrder,
    policy,
    stats,
    categoryCoverage,
    sampleComponents: components.slice(0, 20).map((component) => ({
      slug: component.slug,
      name: component.name,
      category: component.category,
      selector: component.selector,
      source: component.source,
      adapter: component.adapter
    }))
  };

  write(outputPaths.manifest, `${JSON.stringify(manifest, null, 2)}\n`);
  write(outputPaths.summary, `${JSON.stringify(summary, null, 2)}\n`);
}

function main() {
  assert(fs.existsSync(outputPaths.tokens), `${relative(outputPaths.tokens)} does not exist. Run npm run build:tokens:web first.`);

  const registry = readJson(registryPath);
  const contracts = readContracts();
  const cssFiles = readCssOrder();

  buildComponentsCss(cssFiles);
  buildIndexCss();
  copyThemeJs();
  buildManifest(registry, contracts, cssFiles);

  console.log(`Built neutral web adapter: ${relative(outputPaths.entry)}, ${relative(outputPaths.components)}, ${relative(outputPaths.javascript)}, ${relative(outputPaths.manifest)}, ${relative(outputPaths.summary)}.`);
}

main();
