import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = path.join(repoRoot, 'registry.json');
const contractsDir = path.join(repoRoot, 'components', 'contracts');
const shopifyDir = path.join(repoRoot, 'platforms', 'shopify');
const assetsDir = path.join(shopifyDir, 'assets');
const manifestPath = path.join(shopifyDir, 'adapter.manifest.json');
const summaryPath = path.join(shopifyDir, 'adapter.summary.json');
const sourceThemeJsPath = path.join(repoRoot, 'components', 'js', 'theme.js');
const maturityModel = 'shopify-maturity-v1';
const maturityLevels = ['css-ready', 'template-detected', 'schema-ready', 'editor-ready', 'implemented', 'planned'];
const maturityStrategies = [
  'embedded-class-contract',
  'dedicated-liquid-template',
  'section-adapter',
  'theme-block-adapter',
  'snippet-adapter',
  'template-adapter',
  'layout-adapter'
];
const schemaStatuses = ['ready', 'missing', 'invalid', 'duplicate', 'not-required'];
const dataStatuses = ['ready', 'missing', 'needs-target-work', 'not-required'];
const compositionStatuses = ['ready', 'missing', 'not-required'];
const editorPreviewStatuses = ['ready', 'missing', 'blocked', 'needs-target-work', 'not-required'];
const behaviorStatuses = ['accepted', 'needs-target-work', 'not-required'];

const baseCssSources = ['reset.css', 'foundations.css', 'utilities.css'];

const componentCssAssets = [
  { source: 'primitives.css', output: 'primitives.css' },
  { source: 'layout.css', output: 'layout-primitives.css' },
  { source: 'forms.css', output: 'forms.css' },
  { source: 'global.css', output: 'global.css' },
  { source: 'product.css', output: 'product.css' },
  { source: 'collection.css', output: 'collection.css' },
  { source: 'storytelling.css', output: 'storytelling.css' },
  { source: 'marketing.css', output: 'marketing.css' },
  { source: 'cart.css', output: 'cart.css' },
  { source: 'account.css', output: 'account.css' },
  { source: 'blog.css', output: 'blog.css' },
  { source: 'sections.css', output: 'sections.css' },
  { source: 'ceramics.css', output: 'ceramics.css' },
  { source: 'coming-soon.css', output: 'coming-soon.css' },
  { source: 'reviews.css', output: 'reviews.css' },
  { source: 'pages.css', output: 'pages.css' }
];

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function readJson(filePath) {
  return JSON.parse(read(filePath));
}

function relative(filePath) {
  return path.relative(repoRoot, filePath);
}

function assert(errors, condition, message) {
  if (!condition) {
    errors.push(message);
  }
}

function pathExists(errors, filePath) {
  assert(errors, fs.existsSync(filePath), `${relative(filePath)} is missing`);
}

function stylesheetTag(assetName) {
  return `{{ '${assetName}' | asset_url | stylesheet_tag }}`;
}

function validateLayoutLoadOrder(errors, manifest, layoutKey, layoutPath) {
  pathExists(errors, layoutPath);

  if (!fs.existsSync(layoutPath)) {
    return;
  }

  const liquid = read(layoutPath);
  const expected = manifest.loadOrder?.[layoutKey] ?? [];
  let previousIndex = -1;

  for (const asset of expected) {
    const tag = stylesheetTag(asset);
    const index = liquid.indexOf(tag);

    assert(errors, index >= 0, `${relative(layoutPath)} must load ${asset}`);
    assert(errors, index > previousIndex, `${relative(layoutPath)} must load ${asset} in manifest load order`);
    previousIndex = index;
  }
}

function validateBaseCss(errors) {
  const basePath = path.join(assetsDir, 'base.css');
  pathExists(errors, basePath);

  if (!fs.existsSync(basePath)) {
    return;
  }

  const baseCss = read(basePath);
  assert(errors, baseCss.includes('Generated by scripts/build-shopify-adapter.js'), 'platforms/shopify/assets/base.css must be generated by scripts/build-shopify-adapter.js');

  for (const source of baseCssSources) {
    const sourcePath = path.join(repoRoot, 'components', 'css', source);
    pathExists(errors, sourcePath);

    if (!fs.existsSync(sourcePath)) {
      continue;
    }

    assert(errors, baseCss.includes(`/* Source: components/css/${source} */`), `base.css is missing source marker for ${source}`);
    assert(errors, baseCss.includes(read(sourcePath).trimEnd()), `base.css does not include components/css/${source}`);
  }

  const forbiddenTokenDefinitions = [...baseCss.matchAll(/^\s*(--(?:tg-|color-|space-|typo-|font-family|radius-|shadow-|transition-|easing-|opacity-|z-)[a-zA-Z0-9_-]*)\s*:/gm)].map((match) => match[1]);
  assert(errors, forbiddenTokenDefinitions.length === 0, `base.css must not define token values; found ${forbiddenTokenDefinitions.slice(0, 10).join(', ')}`);
}

function validateCopiedAssets(errors) {
  for (const asset of componentCssAssets) {
    const sourcePath = path.join(repoRoot, 'components', 'css', asset.source);
    const outputPath = path.join(assetsDir, asset.output);

    pathExists(errors, sourcePath);
    pathExists(errors, outputPath);

    if (fs.existsSync(sourcePath) && fs.existsSync(outputPath)) {
      assert(errors, read(outputPath) === read(sourcePath), `platforms/shopify/assets/${asset.output} must match components/css/${asset.source}`);
    }
  }

  const themeJsPath = path.join(assetsDir, 'theme.js');
  pathExists(errors, themeJsPath);
  pathExists(errors, sourceThemeJsPath);

  if (fs.existsSync(themeJsPath) && fs.existsSync(sourceThemeJsPath)) {
    assert(errors, read(themeJsPath) === read(sourceThemeJsPath), 'platforms/shopify/assets/theme.js must match components/js/theme.js');
  }
}

function readContracts(errors) {
  const contracts = new Map();
  pathExists(errors, contractsDir);

  if (!fs.existsSync(contractsDir)) {
    return contracts;
  }

  for (const fileName of fs.readdirSync(contractsDir).filter((file) => file.endsWith('.contract.json')).sort()) {
    const contract = readJson(path.join(contractsDir, fileName));
    contracts.set(contract.slug, contract);
  }

  return contracts;
}

function validateManifest(errors, warnings, registry, contracts, manifest) {
  assert(errors, manifest.$schema === 'https://the-gallery.dev/schema/shopify-adapter-manifest.json', 'manifest.$schema is not the expected Shopify adapter schema URL');
  assert(errors, manifest.manifestVersion === '0.1.0', 'manifest.manifestVersion must be 0.1.0');
  assert(errors, manifest.target?.id === 'shopify', 'manifest.target.id must be shopify');
  assert(errors, manifest.generatedBy === 'scripts/build-shopify-adapter.js', 'manifest.generatedBy must be scripts/build-shopify-adapter.js');
  assert(errors, manifest.outputs?.manifest === 'platforms/shopify/adapter.manifest.json', 'manifest.outputs.manifest must point to platforms/shopify/adapter.manifest.json');
  assert(errors, manifest.outputs?.summary === 'platforms/shopify/adapter.summary.json', 'manifest.outputs.summary must point to platforms/shopify/adapter.summary.json');
  assert(errors, manifest.maturityModel?.id === maturityModel, `manifest.maturityModel.id must be ${maturityModel}`);
  for (const layer of ['css', 'liquid', 'schema', 'data', 'behavior', 'templateComposition', 'editorPreview']) {
    assert(errors, typeof manifest.maturityModel?.layers?.[layer] === 'string', `manifest.maturityModel.layers.${layer} must be documented`);
  }
  for (const strategy of maturityStrategies) {
    assert(errors, typeof manifest.maturityModel?.strategies?.[strategy] === 'string', `manifest.maturityModel.strategies.${strategy} must be documented`);
  }

  const registrySlugs = Object.keys(registry.components).sort();
  const manifestComponents = manifest.components ?? [];
  const manifestSlugs = manifestComponents.map((component) => component.slug).sort();

  assert(errors, manifest.stats?.components === registrySlugs.length, `manifest.stats.components must be ${registrySlugs.length}`);
  assert(errors, manifestComponents.length === registrySlugs.length, `manifest.components must contain ${registrySlugs.length} components`);

  const missing = registrySlugs.filter((slug) => !manifestSlugs.includes(slug));
  const extra = manifestSlugs.filter((slug) => !registrySlugs.includes(slug));
  assert(errors, missing.length === 0, `manifest.components missing registry components: ${missing.join(', ')}`);
  assert(errors, extra.length === 0, `manifest.components has extra components: ${extra.join(', ')}`);

  for (const component of manifestComponents) {
    const registryComponent = registry.components[component.slug];
    const contract = contracts.get(component.slug);

    if (!registryComponent || !contract) {
      continue;
    }

    assert(errors, component.name === contract.name, `${component.slug} manifest name must match contract`);
    assert(errors, component.registryId === registryComponent.id, `${component.slug} manifest registryId must match registry`);
    assert(errors, component.category === registryComponent.category, `${component.slug} manifest category must match registry`);
    assert(errors, component.selector === registryComponent.selector, `${component.slug} manifest selector must match registry`);
    assert(errors, component.source?.css === registryComponent.file, `${component.slug} manifest source.css must match registry`);
    assert(errors, component.source?.contract === `components/contracts/${component.slug}.contract.json`, `${component.slug} manifest source.contract must point to contract`);
    assert(errors, component.source?.docs === contract.source.docs, `${component.slug} manifest source.docs must match contract`);
    assert(errors, component.contractAdapter?.status === contract.adapters?.shopify?.status, `${component.slug} manifest Shopify status must match contract`);

    const cssOutput = component.source?.cssOutput;
    assert(errors, typeof cssOutput === 'string' && cssOutput.length > 0, `${component.slug} must map to a Shopify CSS output`);
    if (cssOutput) {
      pathExists(errors, path.join(repoRoot, cssOutput));
    }

    for (const liquidPath of component.liquid?.files ?? []) {
      pathExists(errors, path.join(repoRoot, liquidPath));
    }

    const maturity = component.maturity;
    const cssLayer = maturity?.layers?.css;
    const liquidLayer = maturity?.layers?.liquid;
    const schemaLayer = maturity?.layers?.schema;
    const dataLayer = maturity?.layers?.data;
    const behaviorLayer = maturity?.layers?.behavior;
    const templateCompositionLayer = maturity?.layers?.templateComposition;
    const editorPreviewLayer = maturity?.layers?.editorPreview;
    assert(errors, maturity?.model === maturityModel, `${component.slug} maturity.model must be ${maturityModel}`);
    assert(errors, maturityLevels.includes(maturity?.level), `${component.slug} maturity.level is invalid`);
    assert(errors, maturityStrategies.includes(maturity?.strategy), `${component.slug} maturity.strategy is invalid`);
    assert(errors, typeof maturity?.ready === 'boolean', `${component.slug} maturity.ready must be boolean`);
    assert(errors, cssLayer?.required === true, `${component.slug} maturity CSS layer must be required`);
    assert(errors, cssLayer?.output === cssOutput, `${component.slug} maturity CSS output must match source.cssOutput`);
    assert(errors, cssLayer?.source === registryComponent.file, `${component.slug} maturity CSS source must match registry`);
    assert(errors, cssLayer?.status === 'ready', `${component.slug} maturity CSS layer must be ready`);
    assert(errors, typeof liquidLayer?.required === 'boolean', `${component.slug} maturity Liquid layer must declare required`);

    if (liquidLayer?.required) {
      assert(errors, ['ready', 'missing'].includes(liquidLayer?.status), `${component.slug} required Liquid layer must be ready or missing`);
      assert(errors, liquidLayer.status === (component.liquid?.files?.length > 0 ? 'ready' : 'missing'), `${component.slug} required Liquid layer must match detected Liquid files`);
    } else {
      assert(errors, liquidLayer?.status === 'not-required', `${component.slug} embedded class contract must mark Liquid as not-required`);
    }

    assert(errors, typeof schemaLayer?.required === 'boolean', `${component.slug} maturity schema layer must declare required`);
    assert(errors, schemaStatuses.includes(schemaLayer?.status), `${component.slug} maturity schema status is invalid`);
    assert(errors, typeof dataLayer?.required === 'boolean', `${component.slug} maturity data layer must declare required`);
    assert(errors, dataStatuses.includes(dataLayer?.status), `${component.slug} maturity data status is invalid`);
    assert(errors, typeof templateCompositionLayer?.required === 'boolean', `${component.slug} maturity templateComposition layer must declare required`);
    assert(errors, compositionStatuses.includes(templateCompositionLayer?.status), `${component.slug} maturity templateComposition status is invalid`);
    assert(errors, typeof editorPreviewLayer?.required === 'boolean', `${component.slug} maturity editorPreview layer must declare required`);
    assert(errors, editorPreviewStatuses.includes(editorPreviewLayer?.status), `${component.slug} maturity editorPreview status is invalid`);
    assert(errors, behaviorStatuses.includes(behaviorLayer?.status), `${component.slug} maturity behavior status is invalid`);
    assert(errors, schemaLayer?.required === (maturity?.strategy === 'section-adapter' || maturity?.strategy === 'theme-block-adapter'), `${component.slug} schema requirement must match Shopify strategy`);
    assert(errors, templateCompositionLayer?.required === (maturity?.strategy === 'section-adapter'), `${component.slug} templateComposition requirement must match Shopify strategy`);
    assert(errors, editorPreviewLayer?.required === (maturity?.strategy === 'section-adapter' || maturity?.strategy === 'theme-block-adapter'), `${component.slug} editorPreview requirement must match Shopify strategy`);
    assert(errors, dataLayer?.required === (maturity?.strategy !== 'embedded-class-contract'), `${component.slug} data requirement must match Shopify strategy`);

    for (const file of schemaLayer?.files ?? []) {
      pathExists(errors, path.join(repoRoot, file.path));
    }

    for (const file of component.liquid?.entries ?? []) {
      pathExists(errors, path.join(repoRoot, file.path));
      assert(errors, component.liquid.files.includes(file.path), `${component.slug} liquid.entries must be represented in liquid.files`);
    }

    assert(errors, behaviorLayer?.required === ((contract.behavior?.length ?? 0) > 0), `${component.slug} behavior requirement must match contract behavior`);
    assert(errors, behaviorLayer?.contractItems === (contract.behavior?.length ?? 0), `${component.slug} behavior contract item count must match contract`);
  }

  const warningEntries = manifest.warnings ?? [];
  assert(errors, manifest.warningCount === warningEntries.length, 'manifest.warningCount must match manifest.warnings length');
  for (const entry of warningEntries) {
    warnings.push(`${entry.slug}: ${entry.message}`);
  }
}

function validateSummary(errors, manifest) {
  pathExists(errors, summaryPath);

  if (!fs.existsSync(summaryPath)) {
    return;
  }

  const summary = readJson(summaryPath);
  assert(errors, summary.$schema === 'https://the-gallery.dev/schema/shopify-adapter-summary.json', 'summary.$schema is not the expected Shopify adapter summary schema URL');
  assert(errors, summary.summaryVersion === '0.1.0', 'summary.summaryVersion must be 0.1.0');
  assert(errors, JSON.stringify(summary.stats) === JSON.stringify(manifest.stats), 'summary.stats must match manifest.stats');
  assert(errors, JSON.stringify(summary.maturityModel) === JSON.stringify(manifest.maturityModel), 'summary.maturityModel must match manifest.maturityModel');
  assert(errors, summary.warningCount === manifest.warningCount, 'summary.warningCount must match manifest.warningCount');
  assert(errors, summary.warnings.length <= summary.warningLimit, 'summary.warnings must not exceed summary.warningLimit');
  assert(errors, Array.isArray(summary.categoryCoverage) && summary.categoryCoverage.length > 0, 'summary.categoryCoverage must be a non-empty array');
  assert(errors, Array.isArray(summary.sampleComponents) && summary.sampleComponents.length > 0, 'summary.sampleComponents must be a non-empty array');
}

function main() {
  const errors = [];
  const warnings = [];

  pathExists(errors, manifestPath);
  pathExists(errors, registryPath);

  const contracts = readContracts(errors);

  if (!fs.existsSync(manifestPath) || !fs.existsSync(registryPath)) {
    console.error('Shopify adapter errors:');
    for (const error of errors) {
      console.error(`- ${error}`);
    }
    process.exit(1);
  }

  const registry = readJson(registryPath);
  const manifest = readJson(manifestPath);

  validateLayoutLoadOrder(errors, manifest, 'theme', path.join(shopifyDir, 'layout', 'theme.liquid'));
  validateLayoutLoadOrder(errors, manifest, 'password', path.join(shopifyDir, 'layout', 'password.liquid'));
  validateBaseCss(errors);
  validateCopiedAssets(errors);
  validateManifest(errors, warnings, registry, contracts, manifest);
  validateSummary(errors, manifest);

  if (warnings.length > 0) {
    console.warn('Shopify adapter warnings:');
    for (const warningMessage of warnings) {
      console.warn(`- ${warningMessage}`);
    }
  }

  if (errors.length > 0) {
    console.error('Shopify adapter errors:');
    for (const error of errors) {
      console.error(`- ${error}`);
    }
    process.exit(1);
  }

  console.log(`Validated Shopify adapter: ${manifest.stats.components} components, ${manifest.stats.targetReady} target-ready, ${manifest.stats.dedicatedLiquidReady} dedicated Liquid templates ready, ${manifest.stats.schemaReady}/${manifest.stats.schemaRequired} schema-ready, ${manifest.stats.cssAssets} CSS assets.`);
}

main();
