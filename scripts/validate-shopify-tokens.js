import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webTokensPath = path.join(repoRoot, 'platforms', 'web', 'tokens.css');
const shopifyTokensPath = path.join(repoRoot, 'platforms', 'shopify', 'assets', 'tokens.css');
const shopifyLayouts = [
  path.join(repoRoot, 'platforms', 'shopify', 'layout', 'theme.liquid'),
  path.join(repoRoot, 'platforms', 'shopify', 'layout', 'password.liquid')
];

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function read(filePath) {
  assert(fs.existsSync(filePath), `${path.relative(repoRoot, filePath)} does not exist`);
  return fs.readFileSync(filePath, 'utf8');
}

function assertIncludes(text, expected, filePath) {
  assert(text.includes(expected), `${path.relative(repoRoot, filePath)} missing expected text: ${expected}`);
}

const webTokens = read(webTokensPath);
const shopifyTokens = read(shopifyTokensPath);

assertIncludes(shopifyTokens, 'Shopify token wrapper generated by scripts/build-shopify-tokens.js.', shopifyTokensPath);
assertIncludes(shopifyTokens, 'Generated by scripts/build-web-tokens.js from tokens/source.', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-surface-primary: var(--tg-color-surface-primary);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--space-button-min-height: var(--tg-component-button-min-height);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-button-size: var(--tg-component-button-font-size);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-button-weight: var(--tg-component-button-font-weight);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--radius-button: var(--tg-component-button-radius);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--transition-button-duration: var(--tg-component-button-transition-duration);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--easing-button: var(--tg-component-button-transition-curve);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-border-focus: var(--tg-color-text-primary);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-border-focus-subtle: color-mix(in srgb, var(--color-border-focus) 15%, transparent);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-default-focused-outer-border: var(--color-border-focus-subtle);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-success-unfocused-label: var(--tg-color-feedback-success-default);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-success-focused-inner-border: var(--tg-color-feedback-success-default);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-success-focused-outer-border: var(--tg-color-feedback-success-background);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-warning-unfocused-label: var(--tg-color-feedback-warning-default);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-warning-focused-inner-border: var(--tg-color-feedback-warning-default);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--color-input-warning-focused-outer-border: var(--tg-color-feedback-warning-background);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--space-input-padding-y: var(--tg-component-input-padding-y);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--space-input-icon-gap: var(--tg-component-input-icon-gap);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-label-size: var(--tg-typography-body-small-size);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-label-line-height: var(--tg-typography-body-small-line-height);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-value-size: var(--tg-typography-body-default-size);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-value-line-height: var(--tg-typography-body-default-line-height);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-message-size: var(--tg-typography-body-caption-size);', shopifyTokensPath);
assertIncludes(shopifyTokens, '--typo-input-message-line-height: var(--tg-typography-body-caption-line-height);', shopifyTokensPath);
assert(shopifyTokens.includes(webTokens), 'platforms/shopify/assets/tokens.css should include the generated neutral web token target');

for (const layoutPath of shopifyLayouts) {
  const liquid = read(layoutPath);
  const tokenTag = "{{ 'tokens.css' | asset_url | stylesheet_tag }}";
  const baseTag = "{{ 'base.css' | asset_url | stylesheet_tag }}";
  const tokenIndex = liquid.indexOf(tokenTag);
  const baseIndex = liquid.indexOf(baseTag);

  assert(tokenIndex !== -1, `${path.relative(repoRoot, layoutPath)} must load tokens.css`);
  assert(baseIndex !== -1, `${path.relative(repoRoot, layoutPath)} must load base.css`);
  assert(tokenIndex < baseIndex, `${path.relative(repoRoot, layoutPath)} must load tokens.css before base.css`);
}

console.log('Validated Shopify token wrapper and layout load order.');
