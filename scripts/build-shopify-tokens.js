import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webTokensPath = path.join(repoRoot, 'platforms', 'web', 'tokens.css');
const shopifyTokensPath = path.join(repoRoot, 'platforms', 'shopify', 'assets', 'tokens.css');

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

assert(fs.existsSync(webTokensPath), 'platforms/web/tokens.css does not exist. Run npm run build:tokens:web first.');

const webTokens = fs.readFileSync(webTokensPath, 'utf8');
const header = [
  '/**',
  ' * Do not edit directly.',
  ' * Shopify token wrapper generated by scripts/build-shopify-tokens.js.',
  ' * Source: platforms/web/tokens.css from tokens/source.',
  ' */',
  ''
].join('\n');

fs.mkdirSync(path.dirname(shopifyTokensPath), { recursive: true });
fs.writeFileSync(shopifyTokensPath, `${header}${webTokens}`);

console.log('Built platforms/shopify/assets/tokens.css from platforms/web/tokens.css.');
