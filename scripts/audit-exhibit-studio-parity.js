import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = path.join(repoRoot, 'registry.json');
const contractsDir = path.join(repoRoot, 'components', 'contracts');
const docsDir = path.join(repoRoot, 'site', 'src', 'content', 'components');
const studioDir = path.join(repoRoot, 'site', 'src', 'content', 'studio');
const studioRenderersPath = path.join(repoRoot, 'site', 'src', 'components', 'studio', 'index.ts');
const componentDetailPath = path.join(repoRoot, 'site', 'src', 'pages', 'ComponentDetail.tsx');
const exhibitDocumentPath = path.join(repoRoot, 'site', 'src', 'components', 'ExhibitDocument.tsx');
const evidencePath = path.join(repoRoot, 'docs', 'reports', 'exhibit-studio-evidence.json');
const reportJsonPath = path.join(repoRoot, 'docs', 'reports', 'exhibit-studio-parity.json');
const reportMarkdownPath = path.join(repoRoot, 'docs', 'reports', 'exhibit-studio-parity.md');

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function readJson(filePath) {
  return JSON.parse(read(filePath));
}

function rendererFacts(source) {
  const imports = new Map(
    [...source.matchAll(/^import\s+(\w+)\s+from\s+'\.\/(\w+)'/gm)]
      .map((match) => [match[1], match[2]])
  );
  const map = new Map();
  const entries = source.match(/const studioRenderers[^=]*=\s*\{([\s\S]*?)\n\};/)?.[1] ?? '';

  for (const match of entries.matchAll(/^\s*(?:'([^']+)'|([a-z][a-z0-9-]*)):\s*(\w+),?$/gmi)) {
    const slug = match[1] ?? match[2];
    const renderer = match[3];
    map.set(slug, {
      renderer,
      source: imports.has(renderer)
        ? `site/src/components/studio/${imports.get(renderer)}.tsx`
        : null,
    });
  }

  return map;
}

function markdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function categoryCounts(components) {
  return components.reduce((counts, component) => {
    const current = counts[component.category] ?? { total: 0, shared: 0, visualReviewed: 0 };
    current.total += 1;
    current.shared += Number(component.structuralParity === 'shared');
    current.visualReviewed += Number(component.visualReview === 'pass');
    counts[component.category] = current;
    return counts;
  }, {});
}

function toMarkdown(report) {
  const lines = [
    '# Exhibit–Studio Parity Matrix',
    '',
    'Generated by `npm run audit:exhibit-studio` from current repository facts and the checked visual-evidence manifest.',
    '',
    '> Structural parity means both modes resolve the same registered renderer, definition, fixture, markup, classes, initial state, and behavior. It is not a `stable` certification; visual review remains explicit and human-owned.',
    '',
    '## Summary',
    '',
    '| Metric | Count |',
    '| --- | ---: |',
    `| Registry components | ${report.summary.components} |`,
    `| Shared renderer path | ${report.summary.structurallyShared} |`,
    `| Structural gaps | ${report.summary.structuralGaps} |`,
    `| Desktop and mobile reviewed | ${report.summary.visualReviewed} |`,
    `| Visual review pending | ${report.summary.visualPending} |`,
    `| Interactive components reviewed | ${report.summary.interactionReviewed} |`,
    `| Passive components marked not applicable | ${report.summary.interactionNotApplicable} |`,
    `| Interaction coverage | ${report.summary.interactionCoverage} |`,
    `| Interaction evidence pending | ${report.summary.interactionPending} |`,
    '',
    '## Category progress',
    '',
    '| Category | Components | Shared | Visual reviewed |',
    '| --- | ---: | ---: | ---: |',
  ];

  for (const [category, counts] of Object.entries(report.summary.categories)) {
    lines.push(`| ${markdownCell(category)} | ${counts.total} | ${counts.shared} | ${counts.visualReviewed} |`);
  }

  lines.push(
    '',
    '## Component matrix',
    '',
    '| ID | Component | Category | Renderer | Structure | Desktop | Mobile | Interaction | Contract |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  );

  for (const component of report.components) {
    lines.push(`| ${[
      component.registryId,
      component.name,
      component.category,
      component.renderer.name ?? '—',
      component.structuralParity,
      component.evidence.desktop,
      component.evidence.mobile,
      component.evidence.interaction,
      component.contractStatus,
    ].map(markdownCell).join(' | ')} |`);
  }

  const gaps = report.components.filter((component) => component.structuralFailures.length > 0);
  lines.push('', '## Structural gaps', '');

  if (gaps.length === 0) {
    lines.push('_None detected._');
  } else {
    lines.push('| Component | Failures |', '| --- | --- |');
    for (const component of gaps) {
      lines.push(`| ${markdownCell(component.slug)} | ${markdownCell(component.structuralFailures.join(', '))} |`);
    }
  }

  lines.push(
    '',
    '## Interpretation',
    '',
    '- The first MDX `<Preview>` remains documentation source and fallback only; it is not a second runtime artwork when a registered Studio renderer exists.',
    '- A `pending` visual cell is deliberate. It must not be read as a pass, failure, or maturity promotion.',
    '- Responsive differences caused by the available canvas width are valid when the underlying renderer and initial configuration are the same.',
    '- Product behavior that remains open in `docs/OPEN-QUESTIONS.md` is not invented by this audit.',
    '',
  );

  return lines.join('\n');
}

function main() {
  const registry = readJson(registryPath);
  const rendererRegistry = read(studioRenderersPath);
  const renderers = rendererFacts(rendererRegistry);
  const componentDetail = read(componentDetailPath);
  const exhibitDocument = read(exhibitDocumentPath);
  const evidence = fs.existsSync(evidencePath) ? readJson(evidencePath) : { components: {} };
  const sharedRuntime = componentDetail.includes('ExhibitSharedRendererContext.Provider')
    && componentDetail.includes('Renderer: StudioRenderer')
    && exhibitDocument.includes('<sharedRenderer.Renderer')
    && exhibitDocument.includes('sharedRenderer.definition');

  const components = Object.entries(registry.components).map(([slug, registryComponent]) => {
    const contractPath = path.join(contractsDir, `${slug}.contract.json`);
    const studioPath = path.join(studioDir, `${slug}.studio.json`);
    const docsPath = path.join(docsDir, `${slug}.mdx`);
    const renderer = renderers.get(slug) ?? { renderer: null, source: null };
    const contract = fs.existsSync(contractPath) ? readJson(contractPath) : null;
    const docs = fs.existsSync(docsPath) ? read(docsPath) : '';
    const rendererSourcePath = renderer.source ? path.join(repoRoot, renderer.source) : null;
    const rendererSource = rendererSourcePath && fs.existsSync(rendererSourcePath)
      ? read(rendererSourcePath)
      : '';
    const visualEvidence = evidence.components?.[slug] ?? null;
    const checks = {
      globalSharedRuntime: sharedRuntime,
      contractPresent: Boolean(contract),
      studioDefinitionPresent: fs.existsSync(studioPath),
      studioRendererPresent: Boolean(renderer.renderer && renderer.source),
      studioRendererSourcePresent: Boolean(rendererSourcePath && fs.existsSync(rendererSourcePath)),
      canonicalDocsPresent: fs.existsSync(docsPath),
      mdxArtworkPreviewPresent: /<Preview\b/.test(docs),
    };
    const structuralFailures = Object.entries(checks)
      .filter(([, passed]) => !passed)
      .map(([name]) => name);
    const desktop = visualEvidence?.desktop?.result ?? 'pending';
    const mobile = visualEvidence?.mobile?.result ?? 'pending';
    const interaction = visualEvidence?.interaction?.result ?? 'pending';
    const visualReview = desktop === 'pass' && mobile === 'pass' ? 'pass' : 'pending';

    return {
      slug,
      registryId: registryComponent.id,
      name: registryComponent.name,
      category: registryComponent.category,
      contractStatus: contract?.status ?? 'missing',
      structuralParity: structuralFailures.length === 0 ? 'shared' : 'gap',
      visualReview,
      renderer: {
        name: renderer.renderer,
        source: renderer.source,
        containsEmbeddedDataImage: /data:image\//.test(rendererSource),
      },
      source: {
        contract: path.relative(repoRoot, contractPath),
        studio: path.relative(repoRoot, studioPath),
        docs: path.relative(repoRoot, docsPath),
      },
      runtime: {
        exhibitArtwork: 'registered Studio renderer',
        studioArtwork: 'registered Studio renderer',
        initialDefinition: path.relative(repoRoot, studioPath),
        mdxPreview: 'fallback-and-audit-only',
      },
      evidence: {
        desktop,
        mobile,
        interaction,
        files: visualEvidence?.files ?? [],
        notes: visualEvidence?.notes ?? [],
      },
      checks,
      structuralFailures,
    };
  });

  const report = {
    reportVersion: '1.0.0',
    generatedAt: new Date().toISOString(),
    policy: {
      decision: 'docs/decisions/0087-shared-exhibit-studio-renderer.md',
      automaticStablePromotion: false,
      siteDistRebuilt: false,
    },
    summary: {
      components: components.length,
      structurallyShared: components.filter((component) => component.structuralParity === 'shared').length,
      structuralGaps: components.filter((component) => component.structuralParity === 'gap').length,
      visualReviewed: components.filter((component) => component.visualReview === 'pass').length,
      visualPending: components.filter((component) => component.visualReview !== 'pass').length,
      interactionReviewed: components.filter((component) => component.evidence.interaction === 'pass').length,
      interactionNotApplicable: components.filter((component) => component.evidence.interaction === 'not-applicable').length,
      interactionCoverage: components.filter((component) => ['pass', 'not-applicable'].includes(component.evidence.interaction)).length,
      interactionPending: components.filter((component) => !['pass', 'not-applicable'].includes(component.evidence.interaction)).length,
      categories: categoryCounts(components),
    },
    components,
  };

  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.dirname(reportJsonPath), { recursive: true });
    fs.writeFileSync(reportJsonPath, `${JSON.stringify(report, null, 2)}\n`);
    fs.writeFileSync(reportMarkdownPath, `${toMarkdown(report)}\n`);
  }

  console.log(JSON.stringify(report.summary, null, 2));
}

main();
